/**
 * 站点公告配置
 * ================================================================
 * 全站公告的唯一配置入口，改这一个文件即可控制公告的显示方式。
 *
 * 两种展示模式（mode）：
 *   'modal'    置顶弹窗：带遮罩、页面锁定滚动；右下角有"关闭"与"不再显示"。
 *   'floating' 悬浮窗：固定在屏幕角落的卡片，不打断阅读；右下角只有"收起"。
 *
 * 关闭语义：
 *   「关闭」     纯临时，刷新后重新弹出
 *   「不再显示」 写入 localStorage，之后不再自动出现（点右下角图标可撤回）
 *
 * 保存后 dev 服务器会自动重启并刷新页面。
 * 右下角的圆形图标是隐藏后重新唤起公告的入口，任何模式下都会保留。
 * 想临时看效果（忽略"不再显示"记忆）时，在网址后加 ?notice=preview
 * ================================================================
 */
export default {
  // 总开关，改为 false 即全站隐藏
  enabled: true,

  // 公告标识：改掉它等于"这是一条新公告"，之前关闭过的访客会重新看到
  // 换公告内容（比如这里从"5.0 发布"改成"下载链接故障"）时请一并改 id，否则老访客看不到新公告
  id: '2026-09-download-issue',

  // 展示模式：'modal'（置顶弹窗）或 'floating'（悬浮窗）
  mode: 'modal',

  // 图标风格，可选：'board'（公告板，默认）/ 'megaphone'（喇叭）/ 'bell'（铃铛）/ 'info'（信息）/ 'spark'（光束）
  // 全部为线性 SVG 且跟随主题配色，可自行在 .vitepress/theme/notice-icons.js 中增删
  icon: 'info',

  // 左上角小标签，留空则不显示
  tag: '公告',

  // 标题
  title: '官网主下载链接暂时不可用',

  // 正文，可以是单个字符串，也可以是字符串数组（每项渲染为一段）
  content: [
    '主下载链接当前无法访问，正在处理中，先使用备用链接下载',
    '备用链接速度可能稍慢',
  ],

  // 可选按钮组，theme 支持 'brand'（实心）与 'alt'（描边）
  // 站内链接走无刷新跳转；以 http(s):// 开头的链接会在新标签页打开
  links: [],

  // 不显示公告的页面（可留空数组），支持 /feedback 或 /feedback.html 两种写法
  excludePaths: [],

  // ---- 仅 'modal' 模式生效 ----
  modal: {
    // 用户要求"必须点击关闭按钮"，故两者默认都是 false
    closeOnEsc: false,
    closeOnOverlayClick: false,
    // 弹窗最大宽度（px）
    width: 480,
  },

  // ---- 仅 'floating' 模式生效 ----
  floating: {
    position: 'bottom-right', // 'bottom-right' 或 'bottom-left'
    defaultCollapsed: false,  // 初始是否为收起状态
    offset: 24,               // 距屏幕边缘的距离（px）
  },

  // 控制"不再显示"是否写持久记忆（换 id 即可重新推送；设为 false 则永远不记住）
  // 注意：「关闭」在任何情况下都是纯临时的，刷新后会重新弹出，不写任何存储
  rememberDismiss: true,

  // 延迟多少毫秒出现，0 为立即
  delay: 200,
}
